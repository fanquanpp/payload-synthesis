"""Regenerate the cursor block in src/style.css.

Two cursors, same visual family:
  badge  — the brand emblem (default everywhere)
  busy   — the sparkle-orbit at 55% opacity with a broken orbit
           (cooldown / disabled controls)
"""
import io, math, urllib.parse

INK, RED, CREAM = '#2A2A2A', '#D63A2C', '#F2ECDF'

def uri(inner, hot=16):
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32">'
           + inner + '</svg>')
    enc = urllib.parse.quote(svg, safe="/:=,.()- QqMmLl").replace('#', '%23')
    return 'url("data:image/svg+xml,' + enc + '") ' + str(hot) + ' ' + str(hot) + ', auto'

# ── state 1: the brand badge ────────────────────────────────────────
badge = (
    '<circle cx="16" cy="16" r="14" fill="' + CREAM + '" stroke="' + INK + '" stroke-width="2.4"/>'
    '<circle cx="16" cy="16" r="14" fill="none" stroke="' + INK + '" stroke-width="1" transform="translate(.9 .9)"/>'
    '<circle cx="16" cy="16" r="10.4" fill="' + CREAM + '" stroke="' + RED + '" stroke-width="2.2"/>'
    '<path d="M16 6.4 L20 21.5 L16 18.4 L12 21.5 Z" fill="' + INK + '" stroke="' + INK + '" stroke-width="1"/>'
    '<path d="M9.5 23.6 h13" stroke="' + INK + '" stroke-width="2.2"/>'
    '<circle cx="16" cy="15.6" r="2.4" fill="' + RED + '" stroke="' + INK + '" stroke-width=".8"/>'
)

# ── state 2: sparkle-orbit, dimmed with a broken orbit ─────────────
def arc(t0, t1, steps=36):
    pts = []
    for i in range(steps + 1):
        t = math.radians(t0 + (t1 - t0) * i / steps)
        x = 16 + 12.4 * math.cos(t)
        y = 15 + 5.2 * math.sin(t)
        pts.append((x, y))
    a = math.radians(-33)
    out = []
    for x, y in pts:
        dx, dy = x - 16, y - 15
        out.append((16 + dx * math.cos(a) - dy * math.sin(a),
                    15 + dx * math.sin(a) + dy * math.cos(a)))
    return 'M' + ' L'.join('%.1f %.1f' % p for p in out)

busy = (
    '<g opacity="0.55">'
    '<path d="' + arc(88, 302) + '" fill="none" stroke="' + INK + '" stroke-width="1.9" '
    'stroke-linecap="round" stroke-dasharray="26 12"/>'
    '<path d="M16 3.6 Q18.1 13.9 28.4 16 Q18.1 18.1 16 28.4 Q13.9 18.1 3.6 16 Q13.9 13.9 16 3.6 Z" '
    'fill="' + CREAM + '" stroke="' + INK + '" stroke-width="2" stroke-linejoin="miter"/>'
    '<path d="' + arc(-58, 30) + '" fill="none" stroke="' + INK + '" stroke-width="1.9" stroke-linecap="round"/>'
    '<circle cx="6.6" cy="26" r="1.8" fill="' + RED + '"/>'
    '</g>'
)

css = (
    '/* ═══ cursors (generated by tools/_gen_cursors.py) ═════════════\n'
    '   Two states, one visual family:\n'
    '   · badge — the brand emblem, the default everywhere\n'
    '   · busy  — the sparkle-orbit dimmed to 55% with a broken\n'
    '     orbit; cooldowns and disabled controls                  */\n'
    ':root{ --cursor-badge:' + uri(badge) + ';\n'
    '       --cursor-busy:' + uri(busy) + '; }\n'
    'body{ cursor:var(--cursor-badge) }\n'
    'button,.icon-btn,.lang-btn,.btn,.ladder .spec{ cursor:var(--cursor-badge) }\n'
    '.stage,.stage.arm,#gl{ cursor:var(--cursor-badge) }\n'
    '/* cooldown / disabled: the broken-orbit sparkle */\n'
    '.skill-btn.disabled{ cursor:var(--cursor-busy) !important }\n'
    'button[disabled],.disabled,[aria-disabled="true"]{ cursor:var(--cursor-busy) }\n'
)

p = 'src/style.css'
s = io.open(p, encoding='utf-8').read()
a = s.index('/* ═══ cursors')
io.open(p, 'w', encoding='utf-8').write(s[:a] + css)
print('cursor block rewritten (badge + busy)')
