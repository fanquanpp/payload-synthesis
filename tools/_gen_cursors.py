"""Generate the NASA-punk SVG cursors and append them to style.css."""
import io, urllib.parse

def svg_cursor(inner, hot=16):
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" '
           'viewBox="0 0 32 32">' + inner + '</svg>')
    enc = urllib.parse.quote(svg).replace("'", "%27").replace('"', "%22")
    return 'url("data:image/svg+xml,' + enc + '") ' + str(hot) + ' ' + str(hot) + ', auto'

INK = '%232A2A2A'
RED = '%23D63A2C'
CREAM = '%23ECE5D6'

# default: crosshair — cream/ink arms, red centre pip
default = (
    '<path d="M16 2 v7 M16 23 v7 M2 16 h7 M23 16 h7" stroke="%s" stroke-width="2.6" stroke-linecap="square"/>'
    '<path d="M16 3 v6 M16 23 v6 M3 16 h6 M23 16 h6" stroke="%s" stroke-width="1.1" stroke-linecap="square"/>'
    '<circle cx="16" cy="16" r="4.2" fill="%s" stroke="%s" stroke-width="1.4"/>'
    '<circle cx="16" cy="16" r="1.4" fill="%s"/>'
) % (CREAM, INK, CREAM, INK, RED)

# aiming (drop): open targeting ring with tick marks
aim = (
    '<circle cx="16" cy="16" r="9" fill="none" stroke="%s" stroke-width="2.6"/>'
    '<circle cx="15" cy="15" r="9" fill="none" stroke="%s" stroke-width="1.1"/>'
    '<path d="M16 2 v5 M16 25 v5 M2 16 h5 M25 16 h5" stroke="%s" stroke-width="2.4"/>'
    '<circle cx="16" cy="16" r="1.6" fill="%s"/>'
) % (CREAM, RED, RED, RED)

# reject targeting: red corner brackets + square
reject = (
    '<path d="M9 2 H2 v7 M23 2 h7 v7 M9 30 H2 v-7 M23 30 h7 v-7" stroke="%s" stroke-width="2.8" fill="none"/>'
    '<rect x="13" y="13" width="6" height="6" fill="%s" stroke="%s" stroke-width="1.4"/>'
) % (RED, RED, CREAM)

CUR_DEFAULT = svg_cursor(default)
CUR_AIM = svg_cursor(aim)
CUR_REJECT = svg_cursor(reject)

p = 'src/style.css'
s = io.open(p, encoding='utf-8').read()

# strip a previous generated block if re-running
if '/* ═══ cursors (generated) ' in s:
    a = s.index('/* ═══ cursors (generated) ')
    s = s[:a]

block = (
    '/* ═══ cursors (generated by tools/build_textures.py helpers) ═══\n'
    '   NASA-punk crosshair by default, an open reticle over the bay,\n'
    '   red corner brackets while the purge skill is targeting.      */\n'
    ':root{ --cursor-default:' + CUR_DEFAULT + '; --cursor-aim:' + CUR_AIM + '; --cursor-reject:' + CUR_REJECT + '; }\n'
    'body{ cursor:var(--cursor-default) }\n'
    'button,.icon-btn,.lang-btn,.skill-btn{ cursor:var(--cursor-default) }\n'
    '.stage{ cursor:var(--cursor-aim) }\n'
    '.stage.arm{ cursor:var(--cursor-reject) }\n'
    'a,.btn,.ladder .spec{ cursor:var(--cursor-default) }\n'
)
s += block
io.open(p, 'w', encoding='utf-8').write(s)
print('style.css cursors appended, block', len(block), 'chars')
